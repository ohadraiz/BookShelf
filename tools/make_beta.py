"""Build the beta site: beta.html and assets/beta/ from the working app.html and assets/.

The beta page loads its own copy of every code file (assets/beta/*) and keeps its library
in a separate browser store, so testing in beta never touches the main bookshelf.
Data files (data/library.js) are shared: they are data, not code.

  python tools/make_beta.py           build
  python tools/make_beta.py --check   fail if beta.html or assets/beta/ are out of date

Never edit beta.html or assets/beta/ by hand.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "app.html"
TARGET = ROOT / "beta.html"
ASSETS = ROOT / "assets"
BETA_ASSETS = ASSETS / "beta"

BANNER_CSS = (
    "<style>.beta-flag{background:#5b3b6b;color:#fff;"
    "text-align:center;font:500 13px Heebo,system-ui,sans-serif;padding:4px 8px}</style>\n"
)
BANNER = '<div class="beta-flag" role="note">סביבת בטא - כאן בודקים שינויים. הארון כאן נפרד מהארון באתר הראשי.</div>\n'

HTML_REPLACEMENTS = [
    ("<title>ארון הספרים שלי</title>\n",
     "<title>בטא - ארון הספרים שלי</title>\n<meta name=\"robots\" content=\"noindex\">\n" + BANNER_CSS),
    ("<body>\n", "<body>\n" + BANNER),
]
# Separate browser storage for beta. Each must appear exactly once in its file.
FILE_REPLACEMENTS = {
    "core.js": [("const LS_KEY='bookshelf-local-v1';", "const LS_KEY='bookshelf-beta-v1';")],
    "covers.js": [("indexedDB.open('bookshelf-covers',1)", "indexedDB.open('bookshelf-beta-covers',1)")],
}
GENERATED = "Generated by tools/make_beta.py. Do not edit by hand."


def code_files():
    """Every .js and .css file directly in assets/ (not in assets/beta/)."""
    return sorted(p.name for p in ASSETS.iterdir() if p.is_file() and p.suffix in (".js", ".css"))


def replace_once(text, old, new, where):
    n = text.count(old)
    if n != 1:
        sys.exit(f"make_beta: expected exactly one {old[:50]!r} in {where}, found {n}")
    return text.replace(old, new)


def build():
    """Return {relative path: text} for everything the beta needs."""
    out = {}
    names = code_files()
    for name in names:
        text = (ASSETS / name).read_text(encoding="utf-8")
        for old, new in FILE_REPLACEMENTS.get(name, []):
            text = replace_once(text, old, new, "assets/" + name)
        mark = f"/* {GENERATED} */\n"
        out["assets/beta/" + name] = mark + text
    for name in FILE_REPLACEMENTS:
        if name not in names:
            sys.exit(f"make_beta: assets/{name} is missing")

    html = SOURCE.read_text(encoding="utf-8")
    for old, new in HTML_REPLACEMENTS:
        html = replace_once(html, old, new, "app.html")
    # point every code file at its beta copy; data/ stays shared
    pattern = re.compile(r'((?:src|href)=")assets/(' + "|".join(re.escape(n) for n in names) + r')"')
    html, count = pattern.subn(r'\1assets/beta/\2"', html)
    referenced = set(re.findall(r'(?:src|href)="assets/([^"/]+)"', SOURCE.read_text(encoding="utf-8")))
    missing = referenced - set(names)
    if missing:
        sys.exit("make_beta: app.html loads files that are not in assets/: " + ", ".join(sorted(missing)))
    out["beta.html"] = f"<!-- {GENERATED} -->\n" + html
    return out


def main():
    check = "--check" in sys.argv
    files = build()
    expected = set(files)
    present = {"assets/beta/" + p.name for p in BETA_ASSETS.iterdir()} if BETA_ASSETS.exists() else set()
    stale = [p for p, t in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != t]
    extra = sorted(present - expected)
    if check:
        if stale or extra:
            print("make_beta: out of date:", ", ".join(stale + [x + " (extra)" for x in extra]),
                  "- run python tools/make_beta.py")
            return 1
        print(f"make_beta: beta is up to date ({len(files) - 1} code files)")
        return 0
    BETA_ASSETS.mkdir(parents=True, exist_ok=True)
    for p in extra:
        (ROOT / p).unlink()
    for p, t in files.items():
        (ROOT / p).write_text(t, encoding="utf-8", newline="\n")
    print(f"make_beta: wrote beta.html and {len(files) - 1} files in assets/beta/"
          + (f", removed {len(extra)} old" if extra else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
